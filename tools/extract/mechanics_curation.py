# ------------------------------------------------------------------------------------------------
# Placement: matched in order against each entry's book, chapter (# heading), section (## heading),
# title and the heading on its own line. The first rule that matches places it.
#   area, topic   where it goes (for area 'creation', the topic is the kind of character)
#   section       the part of the topic it opens: a name, '$sec' for the book's section, '$ch' for
#                 its chapter, or None
# ------------------------------------------------------------------------------------------------

def R(book, area, topic, section=None, ch=None, sec=None, title=None, head=None):
    return {
        'book': re.compile(f'^(?:{book})$'), 'area': area, 'topic': topic, 'section': section,
        'ch': re.compile(ch, re.I) if ch else None, 'sec': re.compile(sec, re.I) if sec else None,
        'title': re.compile(title, re.I) if title else None, 'head': re.compile(head, re.I) if head else None,
    }


