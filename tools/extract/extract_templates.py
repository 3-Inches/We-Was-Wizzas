# The core book's character templates (Ars Magica Definitive Edition, Character Templates): six grogs,
# five companions and a magus of each House, written out as stat blocks for app/src/data/templates.ts.
# Run: python3 -I tools/extract/extract_templates.py "reviewed/Ars Magica - Definitive Edition (Core Rules).md" > app/src/data/templates.ts
import json, re, sys

L = open(sys.argv[1], encoding='utf-8').read().split('\n')
start = next(i for i, l in enumerate(L) if l.strip() == '## Character Templates')
end = next(i for i, l in enumerate(L) if l.strip() == '## Detailed Character Creation')
HOUSES = {'Bjornaer': 'bjornaer', 'Bonisagus': 'bonisagus', 'Criamon': 'criamon', 'Ex Miscellanea': 'ex-miscellanea', 'Flambeau': 'flambeau', 'Guernicus': 'guernicus',
          'Jerbiton': 'jerbiton', 'Mercere': 'mercere', 'Merinita': 'merinita', 'Tremere': 'tremere', 'Tytalus': 'tytalus', 'Verditius': 'verditius'}

def clean(s):
    s = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', s)  # links
    s = s.replace('\\*', '*').replace('<br>', ' ').replace('–', '-').replace('−', '-')
    return re.sub(r'\s+', ' ', s).strip()

out = []
kind = None
i = start
while i < end:
    l = L[i]
    if l.startswith('### Grog Templates'): kind = 'grog'
    elif l.startswith('### Companion Templates'): kind = 'companion'
    elif l.startswith('### Magus Templates'): kind = 'magus'
    elif l.startswith('#### ') and kind:
        name = l[5:].strip()
        t = {'id': re.sub(r'[^a-z]+', '-', name.lower().replace('the ', '')).strip('-'), 'name': name, 'type': kind, 'line': i + 1, 'fields': {}, 'spells': []}
        j = i + 1
        field = None
        while j < end and not L[j].startswith('#'):
            m = re.match(r'^([A-Z][A-Za-z ]+):\s*(.*)$', L[j])
            if m and m.group(1) in ('Characteristics', 'Size', 'Age', 'Decrepitude', 'Warping Score', 'Confidence Score', 'Virtues and Flaws', 'Personality Traits', 'Reputations', 'Combat', 'Soak', 'Abilities', 'Arts', 'Twilight Scars', 'Equipment', 'Encumbrance', 'Customization Notes', 'Spells Known', 'Fatigue Levels', 'Wound Penalties'):
                field = m.group(1)
                t['fields'][field] = clean(m.group(2))
            elif field == 'Spells Known' and L[j].startswith('- '):
                # the book's own notation, which the stat-block reader takes as it is: 'Name (TeFo 25/+19)'
                t['spells'].append(re.sub(r'\(\s*\(', '(', clean(L[j][2:])))
            elif field == 'Customization Notes' and L[j].strip() and not L[j].startswith('>'):
                t['fields'][field] += ' ' + clean(L[j])
            j += 1
        f = t['fields']
        # slips in the book's text: a line run on into the next (the Hunter's Flaws and Personality
        # Traits), a missing comma after a House Virtue's mark (the Ex Miscellanea's Giant Blood*)
        vf = f.get('Virtues and Flaws', '')
        if 'Personality Traits:' in vf:
            vf, rest = vf.split('Personality Traits:', 1)
            f['Personality Traits'] = f.get('Personality Traits') or rest.strip()
        f['Virtues and Flaws'] = re.sub(r'\*\s+(?=[A-Z])', '*, ', vf.strip())
        age = re.match(r'(\d+)', f.get('Age', ''))
        rec = {
            'id': t['id'], 'name': name, 'type': kind, 'line': t['line'],
            'house': HOUSES.get(name) if kind == 'magus' else None,
            'age': int(age.group(1)) if age else 25,
            'gender': 'Female' if re.search(r'female|witch', name, re.I) else None,
            'personality': f.get('Personality Traits', ''),
            'notes': f.get('Customization Notes', ''),
            'sheet': {k: v for k, v in {
                'characteristics': f.get('Characteristics', ''),
                'virtues': f.get('Virtues and Flaws', ''),
                'abilities': f.get('Abilities', ''),
                'arts': f.get('Arts'),
                'spells': t['spells'] or None,
                'warping': f.get('Warping Score'),
                'decrepitude': f.get('Decrepitude'),
                'confidence': f.get('Confidence Score'),
                'reputations': None if re.match(r'^none\.?$', f.get('Reputations', ''), re.I) else f.get('Reputations'),
                'equipment': f.get('Equipment'),
                'twilightScars': None if re.match(r'^none\.?$', f.get('Twilight Scars', 'none'), re.I) else f.get('Twilight Scars'),
            }.items() if v},
        }
        out.append(rec)
        i = j
        continue
    i += 1

print('// GENERATED by tools/extract/extract_templates.py from the Definitive Edition, Character Templates: do not edit by hand.')
print('// The core book\'s ready-made characters: six grogs, five companions and a magus of each House, as stat blocks.')
print("import type { StatBlock } from './livingCovenants/types';")
print()
print('export interface CharacterTemplate {')
print('  id: string;\n  name: string;\n  type: \'grog\' | \'companion\' | \'magus\';\n  /** the line of the Definitive Edition it begins on */\n  line: number;\n  house: string | null;\n  age: number;\n  gender: \'Female\' | null;')
print('  /** as the book lists them: "Angry +3, Brave +3, Loyal +1" */\n  personality: string;\n  /** the book\'s Customization Notes */\n  notes: string;\n  sheet: StatBlock;\n}')
print()
print('export const CHARACTER_TEMPLATES: CharacterTemplate[] = ' + json.dumps(out, indent=2, ensure_ascii=False) + ';')
